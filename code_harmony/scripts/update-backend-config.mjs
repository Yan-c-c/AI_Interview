import { mkdirSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { networkInterfaces } from 'os';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(projectRoot, 'entry/src/main/ets/services/GeneratedConfig.ets');

function getLocalIPv4() {
  const nets = networkInterfaces();
  const preferredNames = ['en0', 'en1', 'bridge100'];
  for (const name of preferredNames) {
    const ip = pickAddress(nets[name]);
    if (ip) {
      return ip;
    }
  }
  for (const addresses of Object.values(nets)) {
    const ip = pickAddress(addresses);
    if (ip) {
      return ip;
    }
  }
  return '127.0.0.1';
}

function pickAddress(addresses) {
  if (!addresses) {
    return undefined;
  }
  const ipv4 = addresses.filter((item) => item.family === 'IPv4' && !item.internal);
  return ipv4.find((item) => item.address.startsWith('192.168.'))?.address
    ?? ipv4.find((item) => item.address.startsWith('10.'))?.address
    ?? ipv4.find((item) => item.address.startsWith('172.'))?.address
    ?? ipv4[0]?.address;
}

const explicitUrl = process.env.AI_INTERVIEW_BACKEND_URL;
const ip = process.env.AI_INTERVIEW_BACKEND_IP ?? getLocalIPv4();
const port = process.env.AI_INTERVIEW_BACKEND_PORT ?? '8000';
const backendUrl = explicitUrl ?? `http://${ip}:${port}`;
const candidateUrls = Array.from(new Set([
  backendUrl,
  `http://${ip}:${port}`,
  `http://10.0.2.2:${port}`,
  `http://127.0.0.1:${port}`,
  `http://localhost:${port}`,
]));

const content = `// Auto-generated by scripts/update-backend-config.mjs.
// Do not edit manually. Set AI_INTERVIEW_BACKEND_URL to override.
export const GENERATED_BACKEND_BASE_URL = '${backendUrl}';
export const GENERATED_BACKEND_CANDIDATE_URLS: string[] = ${JSON.stringify(candidateUrls, null, 2)};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, content, 'utf8');
console.log(`[ai-interview] backend URL: ${backendUrl}`);
